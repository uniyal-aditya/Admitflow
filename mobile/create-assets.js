const fs = require('fs');
const path = require('path');

// Create a minimal valid 1x1 PNG (blue pixel)
const pngHeader = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
const ihdr = Buffer.from([0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xDE]);
const idat = Buffer.from([0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, 0x54, 0x08, 0xD7, 0x63, 0xD8, 0xAB, 0xF2, 0x01, 0x00, 0x01, 0x01, 0x00, 0x01, 0x00, 0x1A, 0x0A, 0x26, 0x0A]);
const iend = Buffer.from([0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82]);
const minimalPng = Buffer.concat([pngHeader, ihdr, idat, iend]);

const dir = path.join(__dirname, 'assets', 'images');
const files = ['icon.png', 'splash.png', 'adaptive-icon.png', 'favicon.png'];
files.forEach(f => {
  const fp = path.join(dir, f);
  if (!fs.existsSync(fp)) {
    fs.writeFileSync(fp, minimalPng);
    console.log('Created', fp);
  } else {
    console.log('Exists', fp);
  }
});
console.log('Done');

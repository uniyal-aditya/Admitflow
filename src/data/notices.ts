export const getNoticesByCollege = (collegeId: string): Notice[] =>
  notices.filter((n) => n.collegeId === collegeId);

export const getNoticesByType = (type: string): Notice[] =>
  notices.filter((n) => n.type === type);

export const getActiveNotices = (): Notice[] =>
  notices.filter((n) => computedStatus(n) === "active");

export const getRecentNotices = (days: number = 7): Notice[] => {
  const cutoff = new Date();
  cutoff.setDate(cutoff.getDate() - days);
  return notices.filter((n) => new Date(n.publishedDate) >= cutoff);
};

export const getUpcomingDeadlines = (): Notice[] =>
  notices.filter(
    (n) => n.lastDate && new Date(n.lastDate) > new Date()
  );

export const searchNotices = (query: string): Notice[] => {
  const q = query.toLowerCase();
  return notices.filter(
    (n) =>
      n.title.toLowerCase().includes(q) ||
      n.summary.toLowerCase().includes(q) ||
      n.coursesAffected.some((c) => c.toLowerCase().includes(q)) ||
      n.branchesAffected.some((b) => b.toLowerCase().includes(q))
  );
};
